/**
 * Returns blogs dynamically sorted by createdAt/date descending
 * so that any newly created blog automatically becomes the top featured post.
 */
export function getSortedBlogs(blogs = initialBlogs) {
  return [...blogs].sort((a, b) => {
    const timeA = new Date(a.createdAt || a.date).getTime()
    const timeB = new Date(b.createdAt || b.date).getTime()
    return timeB - timeA
  })
}

/**
 * Find a blog by its slug or id
 */
export function getBlogBySlug(slug, blogs = initialBlogs) {
  if (!slug) return null
  return blogs.find((b) => b.slug === slug || b.id === slug) || null
}
